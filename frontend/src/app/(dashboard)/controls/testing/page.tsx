'use client';

import { useState, useEffect, useMemo, useCallback, Suspense } from 'react';
import Link from 'next/link';
import api from '@/lib/api';
import {
    PageHeader, PageShell, StatusBadge, DataTable,
    AdvancedFilterPanel, ActiveFilterChips, SavedViewMenu,
} from '@/components/ui';
import type { ColumnDef, ActiveFilterChip, AdvancedFilterField } from '@/components/ui';
import { useToast } from '@/components/ui/Toast';

// ─── Types ────────────────────────────────────────────────────────────────────

type BV = 'critical' | 'high' | 'medium' | 'low' | 'info' | 'success' | 'warning' | 'neutral' | 'primary';

interface ControlTest {
    id: string;
    testNo: string;
    controlId: string;
    plannedDate: string;
    completedAt?: string | null;
    status: string;
    findingStatus?: string | null;
    assigneeId?: string | null;
    isAutoGenerated: boolean;
    summary?: string | null;
    year?: number | null;
    periodLabel?: string | null;
    control: {
        id: string;
        controlId: string;
        name: string;
        type: string;
        frequency: string;
        gmy?: string | null;
    };
    directorate?: { id: string; name: string; code?: string | null } | null;
    findings?: { id: string; findingId: string; severity: string; resolutionStatus: string }[];
}

// ─── Config ───────────────────────────────────────────────────────────────────

const statusConfig: Record<string, { label: string; variant: BV }> = {
    BEKLIYOR: { label: 'Bekliyor', variant: 'neutral' },
    DEVAM_EDIYOR: { label: 'Devam Ediyor', variant: 'warning' },
    TAMAMLANDI: { label: 'Onay Bekliyor', variant: 'info' },
    GERI_GONDERILDI: { label: 'Geri Gönderildi', variant: 'critical' },
    ONAYLANDI: { label: 'Onaylandı', variant: 'success' },
    IPTAL: { label: 'İptal Edildi', variant: 'neutral' },
    KAPSAM_DISI: { label: 'Kapsam Dışı', variant: 'neutral' },
};

const findingStatusConfig: Record<string, { label: string; variant: BV }> = {
    BULGUSU_YOK: { label: 'Bulgu Yok', variant: 'success' },
    BULGUSU_VAR: { label: 'Bulgu Var', variant: 'critical' },
};

const fmt = (d?: string | null) => {
    if (!d) return '—';
    const dt = new Date(d);
    return isNaN(dt.getTime()) ? '—' : dt.toLocaleDateString('tr-TR');
};

const MONTHS_TR = ['Ocak', 'Şubat', 'Mart', 'Nisan', 'Mayıs', 'Haziran', 'Temmuz', 'Ağustos', 'Eylül', 'Ekim', 'Kasım', 'Aralık'];
const MONTHS_SHORT = ['Oca', 'Şub', 'Mar', 'Nis', 'May', 'Haz', 'Tem', 'Ağu', 'Eyl', 'Eki', 'Kas', 'Ara'];

/** Gecikmiş testi belirleyen tek predicate — panoyla aynı kural */
const isOverdue = (t: ControlTest) =>
    ['BEKLIYOR', 'DEVAM_EDIYOR'].includes(t.status) && new Date(t.plannedDate) < new Date();

const IconCalendar = ({ className = 'w-3.5 h-3.5' }: { className?: string }) => (
    <svg className={className} fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M8 7V3m8 4V3m-9 8h10M5 21h14a2 2 0 002-2V7a2 2 0 00-2-2H5a2 2 0 00-2 2v12a2 2 0 002 2z" /></svg>
);
const IconWarning = ({ className = 'w-3.5 h-3.5' }: { className?: string }) => (
    <svg className={className} fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M12 9v2m0 4h.01m-6.938 4h13.856c1.54 0 2.502-1.667 1.732-3L13.732 4c-.77-1.333-2.694-1.333-3.464 0L3.34 16c-.77 1.333.192 3 1.732 3z" /></svg>
);
const IconExternal = ({ className = 'w-3.5 h-3.5' }: { className?: string }) => (
    <svg className={className} fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M10 6H6a2 2 0 00-2 2v10a2 2 0 002 2h10a2 2 0 002-2v-4M14 4h6m0 0v6m0-6L10 14" /></svg>
);

// Liste durumu (arama/filtre/sayfa) — test sayfasından "Listeye Dön" ile geri
// gelindiğinde korunur (bkz. görev 1: "Test Listesine Dön önceki filtre/sayfa
// konumunu korusun"). React state route değişiminde sıfırlandığı için sessionStorage
// kullanılıyor.
const LIST_STATE_KEY = 'control-tests-list-state';
interface ListState {
    searchQuery: string;
    activeFilters: Record<string, string>;
    colFilters: Record<string, string>;
    selectedMonth: number | null;
    page: number;
}
const loadListState = (): Partial<ListState> => {
    if (typeof window === 'undefined') return {};
    try {
        const raw = sessionStorage.getItem(LIST_STATE_KEY);
        return raw ? JSON.parse(raw) : {};
    } catch { return {}; }
};

// ─── Page ─────────────────────────────────────────────────────────────────────

function ControlTestingPageContent() {
    const { error: showError } = useToast();
    const initial = useMemo(loadListState, []);

    const [tests, setTests] = useState<ControlTest[]>([]);
    const [loading, setLoading] = useState(true);

    const [searchQuery, setSearchQuery] = useState(initial.searchQuery ?? '');
    const [activeFilters, setActiveFilters] = useState<Record<string, string>>(initial.activeFilters ?? {});
    const [colFilters, setColFilters] = useState<Record<string, string>>(initial.colFilters ?? {});
    // Not: initial.selectedMonth ?? ... KULLANILMAZ — kaydedilmiş "Tümü" (null)
    // ile "hiç kayıt yok" (undefined) birbirine karışır. Anahtarın sessionStorage'da
    // gerçekten var olup olmadığına bakılır.
    const [selectedMonth, setSelectedMonth] = useState<number | null>(
        'selectedMonth' in initial ? (initial.selectedMonth as number | null) : new Date().getMonth()
    );
    const [page, setPage] = useState(initial.page ?? 1);
    const pageSize = 25;

    // Her değişiklikte kalıcı listeleme durumu güncellenir
    useEffect(() => {
        try {
            sessionStorage.setItem(LIST_STATE_KEY, JSON.stringify({ searchQuery, activeFilters, colFilters, selectedMonth, page } as ListState));
        } catch { /* noop */ }
    }, [searchQuery, activeFilters, colFilters, selectedMonth, page]);

    const load = useCallback(async () => {
        setLoading(true);
        try {
            const res = await api.getAllControlTests({ limit: 2000 }) as { data: ControlTest[] };
            setTests(res?.data || []);
        } catch {
            showError('Hata', 'Test kayıtları yüklenemedi.');
            setTests([]);
        } finally {
            setLoading(false);
        }
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, []);

    useEffect(() => { load(); }, [load]);

    const monthFiltered = useMemo(() => {
        if (selectedMonth === null) return tests;
        return tests.filter(t => {
            const d = new Date(t.plannedDate);
            return d.getMonth() === selectedMonth && d.getFullYear() === new Date().getFullYear();
        });
    }, [tests, selectedMonth]);

    const filtered = useMemo(() => {
        return monthFiltered.filter(t => {
            if (searchQuery) {
                const q = searchQuery.toLowerCase();
                const txt = [t.testNo, t.control.controlId, t.control.name, t.directorate?.name, t.summary].filter(Boolean).join(' ').toLowerCase();
                if (!txt.includes(q)) return false;
            }
            if (activeFilters.status && activeFilters.status !== 'all' && t.status !== activeFilters.status) return false;
            if (activeFilters.findingStatus && t.findingStatus !== activeFilters.findingStatus) return false;
            if (activeFilters.directorateId && t.directorate?.id !== activeFilters.directorateId) return false;
            if (activeFilters.overdue === 'evet' && !isOverdue(t)) return false;
            return true;
        });
    }, [monthFiltered, searchQuery, activeFilters]);

    const advancedFields: AdvancedFilterField[] = useMemo(() => [
        {
            type: 'select', key: 'status', label: 'Statü',
            value: activeFilters['status'] || '',
            onChange: (v: string) => { setActiveFilters(p => ({ ...p, status: v })); setPage(1); },
            options: Object.entries(statusConfig).map(([k, v]) => ({ value: k, label: v.label })),
        },
        {
            type: 'select', key: 'findingStatus', label: 'Kontrol Sonucu',
            value: activeFilters['findingStatus'] || '',
            onChange: (v: string) => { setActiveFilters(p => ({ ...p, findingStatus: v })); setPage(1); },
            options: Object.entries(findingStatusConfig).map(([k, v]) => ({ value: k, label: v.label })),
        },
    ], [activeFilters]);

    const filterLabels: Record<string, string> = { status: 'Statü', findingStatus: 'Kontrol Sonucu', overdue: 'Gecikmiş', directorateId: 'Direktörlük' };
    const filterValueLabel = (key: string, value: string): string => {
        if (key === 'status') return statusConfig[value]?.label ?? value;
        if (key === 'findingStatus') return findingStatusConfig[value]?.label ?? value;
        if (key === 'overdue') return 'Evet';
        return value;
    };
    const activeChips: ActiveFilterChip[] = useMemo(() => {
        const chips: ActiveFilterChip[] = [];
        if (searchQuery) chips.push({ key: 'search', label: 'Arama', value: searchQuery, onRemove: () => { setSearchQuery(''); setPage(1); } });
        Object.entries(activeFilters).forEach(([k, v]) => {
            if (v && v !== 'all') chips.push({
                key: k, label: filterLabels[k] ?? k, value: filterValueLabel(k, v),
                onRemove: () => { setActiveFilters(p => ({ ...p, [k]: '' })); setPage(1); },
            });
        });
        return chips;
        // eslint-disable-next-line react-hooks/exhaustive-deps
    }, [searchQuery, activeFilters]);

    const clearAll = () => { setSearchQuery(''); setActiveFilters({}); setColFilters({}); setPage(1); };

    const columns: ColumnDef<ControlTest>[] = useMemo(() => [
        {
            key: 'testNo',
            header: 'Test No',
            sortable: true,
            defaultWidth: 130,
            filter: { type: 'text', placeholder: 'Test No...', fn: (t: ControlTest, v) => t.testNo.toLowerCase().includes(v.toLowerCase()) },
            render: (t) => (
                <Link href={`/controls/testing/${t.id}`} className="font-mono text-xs font-bold text-blue-700 hover:underline">
                    {t.testNo}
                </Link>
            ),
        },
        {
            key: 'control',
            header: 'Kontrol',
            defaultWidth: 260,
            filter: { type: 'text', placeholder: 'Kontrol adı...', fn: (t: ControlTest, v) => (t.control.name + ' ' + t.control.controlId).toLowerCase().includes(v.toLowerCase()) },
            render: (t) => (
                <div className="min-w-0">
                    <p className="text-xs font-semibold text-slate-700 truncate">{t.control.name}</p>
                    <p className="text-[10px] text-slate-400 font-mono">{t.control.controlId}</p>
                </div>
            ),
        },
        {
            key: 'period', header: 'Yıl / Dönem', defaultWidth: 150,
            render: (t) => <span className="text-xs text-slate-600">{t.periodLabel || (t.year ? String(t.year) : '—')}</span>,
        },
        {
            key: 'directorate',
            header: 'Direktörlük',
            sortable: true,
            defaultWidth: 160,
            filter: { type: 'text', placeholder: 'Direktörlük...', fn: (t: ControlTest, v) => (t.directorate?.name || '').toLowerCase().includes(v.toLowerCase()) },
            render: (t) => (
                <span className="text-xs text-slate-600 truncate block max-w-[150px]">{t.directorate?.name || '—'}</span>
            ),
        },
        {
            key: 'plannedDate',
            header: 'Plan Tarihi',
            sortable: true,
            defaultWidth: 110,
            render: (t) => {
                const overdue = isOverdue(t);
                return (
                    <span className={`inline-flex items-center gap-1 text-xs font-medium ${overdue ? 'text-red-600' : 'text-slate-700'}`}>
                        {fmt(t.plannedDate)}
                        {overdue && <IconWarning className="w-3 h-3" />}
                    </span>
                );
            },
        },
        {
            key: 'status',
            header: 'Statü',
            sortable: true,
            defaultWidth: 140,
            filter: { type: 'select', options: Object.entries(statusConfig).map(([k, v]) => ({ value: k, label: v.label })), fn: (t: ControlTest, v) => t.status === v },
            render: (t) => {
                const sc = statusConfig[t.status];
                const fc = t.findingStatus ? findingStatusConfig[t.findingStatus] : null;
                return (
                    <div className="flex flex-col gap-1">
                        {sc && <StatusBadge variant={sc.variant}>{sc.label}</StatusBadge>}
                        {fc && <StatusBadge variant={fc.variant} dot>{fc.label}</StatusBadge>}
                    </div>
                );
            },
        },
        {
            key: 'findings',
            header: 'Bulgular',
            defaultWidth: 80,
            render: (t) => {
                const cnt = t.findings?.length || 0;
                return cnt > 0
                    ? <span className="px-2 py-0.5 bg-red-100 text-red-700 text-xs font-bold rounded-full border border-red-200">{cnt}</span>
                    : <span className="text-slate-300 text-xs">—</span>;
            },
        },
        {
            key: 'actions',
            header: '',
            defaultWidth: 90,
            render: (t) => (
                <Link
                    href={`/controls/testing/${t.id}`}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="inline-flex items-center gap-1 px-2 py-1 text-[11px] font-bold text-slate-500 hover:text-blue-600 hover:bg-blue-50 rounded transition-colors"
                    title="Testi Aç (yeni sekmede)"
                >
                    Testi Aç <IconExternal className="w-3 h-3" />
                </Link>
            ),
        },
    ], []);

    const colFiltered = useMemo(() => {
        if (!Object.values(colFilters).some(v => v)) return filtered;
        return filtered.filter(t => columns.every(col => {
            const val = colFilters[col.key];
            return !val || !col.filter?.fn || col.filter.fn(t, val);
        }));
    }, [filtered, colFilters, columns]);

    const paginated = useMemo(() => colFiltered.slice((page - 1) * pageSize, page * pageSize), [colFiltered, page]);

    return (
        <PageShell>
            <PageHeader
                title="Kontrol Testleri"
                description="Kontrollere ait test kayıtlarını yönetin — bir test seçip geniş çalışma sayfasında açın"
                breadcrumbs={[{ label: 'Kontrol Testleri' }]}
            />

            {/* Ay seçici */}
            <div className="flex flex-wrap items-center gap-2 mb-3">
                <span className="inline-flex items-center gap-1.5 text-xs font-medium text-slate-400 mr-1">
                    <IconCalendar className="w-3.5 h-3.5" />
                    Ay:
                </span>
                <button
                    type="button"
                    onClick={() => { setSelectedMonth(null); setPage(1); }}
                    aria-pressed={selectedMonth === null}
                    className={`inline-flex items-center h-8 px-3 rounded-full text-xs font-medium border transition-colors duration-150 cursor-pointer ${selectedMonth === null
                        ? 'bg-blue-600 border-blue-600 text-white shadow-sm'
                        : 'bg-white border-slate-200 text-slate-600 hover:border-blue-300 hover:text-blue-700 hover:bg-blue-50/50'
                        }`}
                >
                    Tümü
                </button>
                {MONTHS_SHORT.map((m, i) => {
                    const isCurrentMonth = i === new Date().getMonth();
                    return (
                        <button
                            key={i}
                            type="button"
                            onClick={() => { setSelectedMonth(i); setPage(1); }}
                            aria-pressed={selectedMonth === i}
                            className={`inline-flex items-center h-8 px-2.5 rounded-full text-xs font-medium border transition-colors duration-150 cursor-pointer ${selectedMonth === i
                                ? 'bg-blue-600 border-blue-600 text-white shadow-sm'
                                : isCurrentMonth
                                    ? 'bg-blue-50 border-blue-200 text-blue-700 hover:bg-blue-100'
                                    : 'bg-white border-slate-200 text-slate-600 hover:border-blue-300 hover:text-blue-700 hover:bg-blue-50/50'
                                }`}
                            title={MONTHS_TR[i]}
                        >
                            {m}
                        </button>
                    );
                })}
            </div>

            {/* Not: İstatistik kartları/grafikleri bu ekrandan kaldırıldı —
                bkz. Kontrol Takip Panosu (Panel görünümü). Değerlendirme çalışması
                artık ayrı bir sayfada: bir satıra tıklayınca /controls/testing/[id] açılır. */}

            <AdvancedFilterPanel
                searchValue={searchQuery}
                onSearchChange={v => { setSearchQuery(v); setPage(1); }}
                searchPlaceholder="Test No, Kontrol adı, Direktörlük ara..."
                fields={advancedFields}
                activeCount={Object.values(activeFilters).filter(v => v && v !== 'all').length}
                onClearAll={clearAll}
            />

            <ActiveFilterChips chips={activeChips} onClearAll={clearAll} />

            <DataTable
                columns={columns}
                data={paginated}
                rowKey={t => t.id}
                loading={loading}
                totalCount={colFiltered.length}
                page={page}
                pageSize={pageSize}
                onPageChange={setPage}
                storageKey="control-tests-v2"
                emptyTitle="Test kaydı bulunamadı"
                emptyDescription="Kontrolleri kapsama alarak test kayıtlarını otomatik oluşturun."
                columnFilters={colFilters}
                onColumnFilterChange={(k, v) => { setColFilters(p => ({ ...p, [k]: v })); setPage(1); }}
                stickyFirstColumn
                onRefresh={load}
                toolbar={
                    <SavedViewMenu
                        storageKey="control-tests-v2"
                        getPayload={() => ({ search: searchQuery, filters: activeFilters, columnFilters: colFilters, selectedMonth })}
                        onApply={(p) => {
                            setSearchQuery(typeof p.search === 'string' ? p.search : '');
                            setActiveFilters((p.filters as Record<string, string>) || {});
                            setColFilters((p.columnFilters as Record<string, string>) || {});
                            setSelectedMonth(typeof p.selectedMonth === 'number' ? p.selectedMonth : null);
                            setPage(1);
                        }}
                    />
                }
            />
        </PageShell>
    );
}

export default function ControlTestingPage() {
    return (
        <Suspense fallback={<PageShell><div className="p-6 text-center text-sm text-slate-500">Yükleniyor...</div></PageShell>}>
            <ControlTestingPageContent />
        </Suspense>
    );
}
